#!/usr/bin/env python3
"""Generates the token outputs from docs/design/tokens.json (stdlib only).

Usage (from anywhere):
  python3 docs/design/gen-tokens.py           write both outputs (only files whose text changes)
  python3 docs/design/gen-tokens.py --check   write nothing; exit 1 if any output or cross-check differs

Outputs:
  assets/theme/app.qss     the token comment block at the top (DESIGN.md sections 2 and 3),
                           from the dashed line above "COLOUR TOKENS" through the
                           "Application font" line. The rest of the file is not touched.
  web/src/ui/theme.css     CSS custom properties for the web version (DESIGN-WEB.md section 2)
                           and one class per type role.

Cross-checks run by --check (read only; they never write):
  - src/ui/Theme.h: every `inline const QColor <name>(0xRRGGBB);` equals tokens.json.
  - assets/theme/app.qss: every #RRGGBB in the style rules is a token value.
  - docs/design/mockup/build.py: its T dict and ROLES table equal tokens.json.
  - type lineHeight: equals round(ascent) + round(descent) from the font files' hhea table,
    which is what QFontMetrics gives and what the web sets as line-height.
"""

import json
import os
import re
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
TOKENS = os.path.join(HERE, "tokens.json")
QSS = os.path.join(ROOT, "assets", "theme", "app.qss")
CSS = os.path.join(ROOT, "web", "src", "ui", "theme.css")
THEME_H = os.path.join(ROOT, "src", "ui", "Theme.h")
MOCKUP = os.path.join(ROOT, "docs", "design", "mockup", "build.py")

DASH = " * " + "-" * 82


def load():
    with open(TOKENS, encoding="utf-8") as f:
        return json.load(f)


def roles(tok, key):
    return {k: v for k, v in tok[key].items() if not k.startswith("_")}


def spacing_text(role):
    if "cells" in role:
        return "cells"
    s = role["spacing"]
    return "0" if s == 0 else f"{float(s):.1f}"


# ------------------------------------------------------------------ app.qss block
def qss_block(tok):
    out = [DASH,
           " * COLOUR TOKENS (DESIGN.md section 2). No other colours appear anywhere.",
           DASH]
    for g in tok["colorGroups"]:
        out.append(f" * {g['id']} {g['title']}")
        for name, c in tok["colors"].items():
            if c["group"] == g["id"]:
                out.append(f" *   {name:<18}{c['hex']}  {c['qss']}")
    out += [" *",
            DASH,
            ' * TYPE ROLES (DESIGN.md section 3). Family "Inter" (assets/fonts, OFL 1.1), sizes in',
            ' * px. Weight 400 = Regular, 500 = Medium. "Caps" strings are stored in capitals by the',
            " * code: QSS cannot change case.",
            DASH,
            f" *   {'role':<18}{'weight':<8}{'size':<6}{'spacing':<9}{'case':<12}colour"]
    for name, r in roles(tok, "type").items():
        out.append(f" *   {'type.' + name:<19}{r['weight']:<8}{r['size']:<6}{spacing_text(r):<9}"
                   f"{r['case']:<12}{r['colour']}")
    af = tok["font"]["appFont"]
    face = {400: "Regular", 500: "Medium"}[af["weight"]]
    out.append(f" * Application font (Theme): {tok['font']['family']} {face} {af['size']} px.")
    return out


def qss_text(tok, current):
    lines = current.split("\n")
    head = next(i for i, l in enumerate(lines) if l.startswith(" * COLOUR TOKENS")) - 1
    tail = next(i for i, l in enumerate(lines) if l.startswith(" * Application font"))
    assert lines[head] == DASH, "app.qss: expected the dashed line above COLOUR TOKENS"
    return "\n".join(lines[:head] + qss_block(tok) + lines[tail + 1:])


# ------------------------------------------------------------------ theme.css
def css_num(v):
    return f"{v:g}"


def hex_rgb(h):
    return tuple(int(h[i:i + 2], 16) for i in (1, 3, 5))


def css_text(tok):
    fam = tok["font"]["family"]
    stack = ", ".join([f'"{fam}"'] + [f'"{f}"' if " " in f else f for f in tok["font"]["fallback"]])
    o = ["/*",
         " * Generated by docs/design/gen-tokens.py from docs/design/tokens.json. Do not edit:",
         " * change tokens.json and run the generator. Names are the DESIGN.md token names.",
         " * Colours: --<token>. Type roles: --type-<role>-{weight,size,spacing,line} and the",
         " * class .type-<role> (font, letter spacing, line height and the role's colour when",
         ' * it has one; "caps" strings are stored in capitals by the code, never text-transform).',
         " * Sizes: --size-<layout>-<name> in px. Breakpoints are listed for reference only:",
         " * custom properties cannot be used inside media queries.",
         " */",
         "",
         ":root {",
         "  color-scheme: dark;",
         f"  --font-family: {stack};"]
    for g in tok["colorGroups"]:
        o.append(f"  /* {g['id']} {g['title']} */")
        for name, c in tok["colors"].items():
            if c["group"] == g["id"]:
                o.append(f"  --{name}: {c['hex']};")
    o.append("  /* web only (DESIGN-WEB.md 2) */")
    for name, c in tok["webColors"].items():
        if name.startswith("_"):
            continue
        r, g, b = hex_rgb(tok["colors"][c["base"]]["hex"])
        o.append(f"  --{name}: rgba({r}, {g}, {b}, {css_num(c['alpha'])});")
    for key in ("type", "webType"):
        o.append(f"  /* {'type roles (DESIGN.md 3.2)' if key == 'type' else 'web type roles (DESIGN-WEB.md 3)'} */")
        for name, r in roles(tok, key).items():
            o.append(f"  --type-{name}-weight: {r['weight']};")
            o.append(f"  --type-{name}-size: {r['size']}px;")
            o.append(f"  --type-{name}-spacing: {css_num(r['spacing'])}px;")
            o.append(f"  --type-{name}-line: {r['lineHeight']}px;")
            if "cells" in r:
                o.append(f"  --type-{name}-cell: {r['cells']}px;")
    for layout, sizes in tok["size"].items():
        if layout.startswith("_"):
            continue
        o.append(f"  /* sizes: {layout} */")
        for name, v in sizes.items():
            o.append(f"  --size-{layout}-{name}: {css_num(v)}px;")
    o.append("}")
    o.append("")
    bp = {k: v for k, v in tok["breakpoints"].items() if not k.startswith("_")}
    o.append("/* breakpoints (px): " + ", ".join(f"{k} {v}" for k, v in bp.items()) + " */")
    o.append("")
    for key in ("type", "webType"):
        for name, r in roles(tok, key).items():
            o.append(f".type-{name} {{")
            o.append(f"  font-family: var(--font-family);")
            o.append(f"  font-weight: var(--type-{name}-weight);")
            o.append(f"  font-size: var(--type-{name}-size);")
            o.append(f"  letter-spacing: var(--type-{name}-spacing);")
            o.append(f"  line-height: var(--type-{name}-line);")
            if r["colour"] in tok["colors"]:
                o.append(f"  color: var(--{r['colour']});")
            o.append("}")
    o.append("")
    return "\n".join(o)


# ------------------------------------------------------------------ cross-checks
def check_theme_h(tok, errors):
    if not os.path.exists(THEME_H):
        errors.append("src/ui/Theme.h not found")
        return
    text = open(THEME_H, encoding="utf-8").read()
    found = dict(re.findall(r"inline const QColor (\w+)\(0x([0-9A-Fa-f]{6})\);", text))
    for name, c in tok["colors"].items():
        v = found.pop(name, None)
        if v is None:
            errors.append(f"Theme.h: no QColor {name}")
        elif "#" + v.upper() != c["hex"].upper():
            errors.append(f"Theme.h: {name} is #{v.upper()}, tokens.json {c['hex']}")
    for name in found:
        errors.append(f"Theme.h: QColor {name} is not a token")


def check_qss_hexes(tok, qss, errors):
    body = qss[qss.index("*/") + 2:]
    allowed = {c["hex"].upper() for c in tok["colors"].values()}
    for h in sorted(set(x.upper() for x in re.findall(r"#[0-9A-Fa-f]{6}\b", body))):
        if h not in allowed:
            errors.append(f"app.qss rules use {h}, which is not a token")


def check_mockup(tok, errors):
    if not os.path.exists(MOCKUP):
        return
    text = open(MOCKUP, encoding="utf-8").read()
    t = dict(re.findall(r'(\w+)="(#[0-9A-Fa-f]{6})"', text[text.index("T = dict("):text.index("ROLES =")]))
    want = {k: v["hex"] for k, v in tok["colors"].items()}
    if {k: v.upper() for k, v in t.items()} != {k: v.upper() for k, v in want.items()}:
        errors.append("mockup/build.py: T dict differs from tokens.json colours")
    rt = dict((m[0], (int(m[1]), int(m[2]), float(m[3]))) for m in
              re.findall(r'"(\w+)": \((\d+), (\d+), ([\d.]+)\)', text[text.index("ROLES ="):]))
    for name, r in roles(tok, "type").items():
        if rt.get(name) != (r["weight"], r["size"], float(r["spacing"])):
            errors.append(f"mockup/build.py: ROLES[{name}] is {rt.get(name)}, tokens.json "
                          f"{(r['weight'], r['size'], float(r['spacing']))}")


def hhea(path):
    data = open(path, "rb").read()
    num = struct.unpack(">H", data[4:6])[0]
    tables = {}
    for i in range(num):
        tag, _, off, _ = struct.unpack(">4sIII", data[12 + 16 * i: 28 + 16 * i])
        tables[tag.decode()] = off
    upm = struct.unpack(">H", data[tables["head"] + 18: tables["head"] + 20])[0]
    asc, desc = struct.unpack(">hh", data[tables["hhea"] + 4: tables["hhea"] + 8])
    return upm, asc, desc


def check_line_heights(tok, errors):
    for key in ("type", "webType"):
        for name, r in roles(tok, key).items():
            path = os.path.join(ROOT, tok["font"]["files"][str(r["weight"])])
            upm, asc, desc = hhea(path)
            lh = round(asc * r["size"] / upm) + round(-desc * r["size"] / upm)
            if lh != r["lineHeight"]:
                errors.append(f"{key}.{name}: lineHeight {r['lineHeight']}, the font gives {lh}")


# ------------------------------------------------------------------ main
def main(argv):
    check = "--check" in argv
    tok = load()
    errors = []
    qss_now = open(QSS, encoding="utf-8").read()
    outputs = [(QSS, qss_now, qss_text(tok, qss_now)),
               (CSS, open(CSS, encoding="utf-8").read() if os.path.exists(CSS) else None, css_text(tok))]
    for path, now, new in outputs:
        rel = os.path.relpath(path, ROOT)
        if now == new:
            print(f"unchanged  {rel}")
        elif check:
            errors.append(f"{rel} is out of date (run docs/design/gen-tokens.py)")
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w", encoding="utf-8", newline="\n") as f:
                f.write(new)
            print(f"wrote      {rel}")
    if check:
        check_theme_h(tok, errors)
        check_qss_hexes(tok, qss_now, errors)
        check_mockup(tok, errors)
        check_line_heights(tok, errors)
    for e in errors:
        print("ERROR", e, file=sys.stderr)
    if check and not errors:
        print("check ok: app.qss, theme.css, Theme.h, mockup/build.py and line heights agree with tokens.json")
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
